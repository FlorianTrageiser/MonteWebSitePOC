<!-- wp:group {"className":"topic","layout":{"type":"default"}} -->
<div class="wp-block-group topic">
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Kinderkrippe</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>In der Krippe kommen Montessori-Materialien und die beziehungsorientierte Pflege nach Emmi Pikler zusammen. Schon beim Anziehen und Wickeln haben die Kinder Zeit, selbst mitzumachen. Bewegung und freies Spiel gehören zum Tagesablauf.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"topic-links"} -->
<p class="topic-links"><a class="more" href="https://www.montessori-erding.de/wp-content/uploads/2026/01/final_Monte_ED_Konzept_Kinderkrippe_2025.pdf" target="_blank" rel="noopener">Konzept Kinderkrippe (PDF) <svg class="ico" viewBox="0 0 24 24" aria-hidden="true"><path d="M5 12h13m-5-6 6 6-6 6" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/></svg></a></p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
<!-- wp:group {"className":"topic","layout":{"type":"default"}} -->
<div class="wp-block-group topic">
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Kindergarten</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Kinder von drei bis sechs Jahren verbringen ihren Tag in vier Gruppen. Nach dem Morgenkreis wählen sie in der Freiarbeit Material und Spielpartner. Gartenzeit und gemeinsame Projekte ergänzen den Vormittag.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"topic-links"} -->
<p class="topic-links"><a class="more" href="https://www.montessori-erding.de/wp-content/uploads/2026/01/Monte_ED_Konzept_Kindergarten_2026.pdf" target="_blank" rel="noopener">Konzept Kindergarten (PDF) <svg class="ico" viewBox="0 0 24 24" aria-hidden="true"><path d="M5 12h13m-5-6 6 6-6 6" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/></svg></a></p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
<!-- wp:group {"className":"topic","layout":{"type":"default"}} -->
<div class="wp-block-group topic">
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Pädagogik</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Die Kinder wählen ihr Arbeitsmaterial selbst und entscheiden, wie lange sie sich damit beschäftigen. Das Team gestaltet die Umgebung so, dass Kinder mit unterschiedlichen Fähigkeiten am Alltag teilnehmen können.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
<!-- wp:group {"className":"topic","layout":{"type":"default"}} -->
<div class="wp-block-group topic">
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Unser Haus</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Das Kinderhaus ist ein zertifiziertes Passivhaus mit Gründach. Jede Gruppe hat eigenen Zugang zum Garten – über Terrasse, Veranda oder Balkon. Dazu kommen Werkraum, Bewegungsraum und ein gut ausgestatteter Therapieraum.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
<!-- wp:group {"className":"topic","layout":{"type":"default"}} -->
<div class="wp-block-group topic">
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Eltern im Kinderhaus</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Eltern und Team tauschen sich regelmäßig über das Kind aus. Familien bringen ihre Fähigkeiten und Ideen in die Arbeit des Kinderhauses ein.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"topic-links"} -->
<p class="topic-links"><a class="more" href="https://montessori-erding.de/wp-content/uploads/2022/10/Kinderhaus_Handzettel_Elternarbeit.pdf" target="_blank" rel="noopener">Handzettel Elternarbeit (PDF) <svg class="ico" viewBox="0 0 24 24" aria-hidden="true"><path d="M5 12h13m-5-6 6 6-6 6" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/></svg></a></p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
<!-- wp:group {"className":"topic","layout":{"type":"default"}} -->
<div class="wp-block-group topic">
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Wie lernen Kinder mit Montessori-Material?</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Sie wählen eine Tätigkeit selbst, wiederholen sie und probieren in ihrem Tempo. Erwachsene beobachten und zeigen bei Bedarf den nächsten Schritt.</p>
<!-- /wp:paragraph -->
</div>
