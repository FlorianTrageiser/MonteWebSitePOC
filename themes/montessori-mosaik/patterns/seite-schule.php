<!-- /wp:heading -->
</div>
<!-- /wp:group -->
<!-- wp:group {"className":"accordion","layout":{"type":"default"}} -->
<div class="wp-block-group accordion">
<!-- wp:details {"className":"acc","showContent":true} -->
<details class="wp-block-details acc" open><summary>Unterricht</summary>
<!-- wp:paragraph -->
<p>Der Vormittagsunterricht dauert von 8:30 bis 12:45 Uhr. In altersgemischten Lerngruppen lernen Kinder voneinander. In höheren Stufen kommt Nachmittagsunterricht hinzu.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details {"className":"acc"} -->
<details class="wp-block-details acc"><summary>Pädagogik</summary>
<!-- wp:paragraph -->
<p>Freiarbeit gibt den Kindern Raum, Verantwortung für ihre Arbeit zu übernehmen. Berichte zum Entwicklungs- und Lernprozess machen Fortschritte sichtbar.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"acc-links"} -->
<p class="acc-links"><a class="more" href="https://www.montessori-erding.de/wp-content/uploads/2022/10/21FragenAnMontessoriSchulen.pdf" target="_blank" rel="noopener">21 Fragen an Montessori-Schulen (PDF)</a></p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details {"className":"acc"} -->
<details class="wp-block-details acc"><summary>Schulleben</summary>
<!-- wp:paragraph -->
<p>Beim Schach planen Kinder ihre nächsten Züge, im Zirkus trainieren sie gemeinsam in der Sporthalle. Im Schülerladen „Mandala“ erproben Jugendliche den Alltag eines Betriebs – vom Verkauf bis zur Buchführung.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"acc-links"} -->
<p class="acc-links"><a class="more" href="https://montessori-erding.de/schule/schulleben/schach/schach-im-schulalltag/">Schach im Schulalltag</a></p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details {"className":"acc"} -->
<details class="wp-block-details acc"><summary>Ganztag</summary>
<!-- wp:paragraph -->
<p>Für den ersten bis dritten Jahrgang gehört die Mittagsvilla zum Angebot. Dazu kommen Arbeitsgemeinschaften am Nachmittag.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"acc-links"} -->
<p class="acc-links"><a class="more" href="https://montessori-erding.de/schule/ganztagesschule/ag-beschreibung/">AG-Beschreibungen</a> <a class="more" href="https://montessori-erding.de/schule/ganztagesschule/faq-ogts/">FAQ Ganztag</a></p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details {"className":"acc"} -->
<details class="wp-block-details acc"><summary>Nachhaltigkeit</summary>
<!-- wp:paragraph -->
<p>Auf dem Schulacker mit der GemüseAckerdemie und in Fairtrade-Projekten wird Nachhaltigkeit praktisch erfahrbar. Die Schule engagiert sich außerdem bei UNESCO und „Schule ohne Rassismus – Schule mit Courage“.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"acc-links"} -->
<p class="acc-links"><a class="more" href="https://montessori-erding.de/schule/bildung-fuer-nachhaltige-entwicklung/ackerschule/">AckerSchule</a></p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details {"className":"acc"} -->
<details class="wp-block-details acc"><summary>Bildungsweg</summary>
<!-- wp:paragraph -->
<p>Auf das Kinderhaus folgen die Schulstufen in Aufkirchen. Eine weiterführende Möglichkeit ist die Montessori-Fachoberschule München, die unser Verein 2007 gemeinsam mit anderen Montessori-Vereinen gegründet hat.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"acc-links"} -->
<p class="acc-links"><a class="more" href="https://www.mos-muenchen.de/">mos-muenchen.de</a></p>
<!-- /wp:paragraph -->
</details>
