<h3 class="wp-block-heading">Ganztag</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Für den ersten bis dritten Jahrgang gehört die Mittagsvilla zum Angebot. Dazu kommen Arbeitsgemeinschaften am Nachmittag.</p>
<!-- /wp:paragraph -->
